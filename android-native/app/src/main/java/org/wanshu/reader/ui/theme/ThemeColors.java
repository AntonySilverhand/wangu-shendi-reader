package org.wanshu.reader.ui.theme;

public class ThemeColors {
    public final int background;
    public final int text;
    public final int secondaryText;
    public final int barBackground;
    public final int border;

    public ThemeColors(int background, int text, int secondaryText, int barBackground, int border) {
        this.background = background;
        this.text = text;
        this.secondaryText = secondaryText;
        this.barBackground = barBackground;
        this.border = border;
    }
}
